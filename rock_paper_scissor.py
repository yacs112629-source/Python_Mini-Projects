#ROCK, PAPER, SCISSOR -----Game 😊
'''
WORKFLOW OF PROJECT
1- Input from user(Rock, Paper, Scissor)
2- Computer Choice(computer will choose randomly not conditionally)
3- Result Print

CASES
A- Rock
U      C
Rock   Rock --> Tie
Rock   Paper ---> C wins
Paper  Rock  ---> U wins


B- Paper
U      C
Paper  Paper --> Tie
Paper  Rock ---> U wins
Rock   Paper ---> C wins

C- Scissor
U      C
Scissor  Scissor --> Tie
Scissor  Rock ---> C wins
Rock   Scissor ---> U wins


'''

#Logic Behind Game
import random
print("--------- Welcome To Hand-Wars 🥷🏻 ----------")
print("-----ROCK = R , PAPER = P , SCISSOR = S -----")
print("--------------------------------------------")
U = input("Enter Your Move ? \n ")
C = random.choice(["R","P","S"])

print(f"Your Move : {U}")
print(f"Computer Move : {C}")

if U == C:
  print("Guess What It's Tieeeee 😂")
elif U == "R":
  if C == "P":
    print("Paper Covers Rock So Computer Wins🏆")
  else:
    print("Rock breaks Scissor So You Win🏆🎉🎉")
elif U == "P":
  if C == "R":
    print("Paper Covers Rock So You Win🏆🎉🎉")
  else:
    print("Scissor Cuts Paper So Computer Wins🏆")
elif U == "S":
  if C == "R":
    print("Rock breaks Scissor So Computer Wins🏆")
  else:
    print("Scissor Cuts Paper So You Win🏆🎉🎉")
else:
  print("Invalid Input Choose only Between[R, P, S]")