#Inputs form users --->
#How many people are there in the group?
#Total amount of money spent on food oder, rent, electricity units ?
#Electricity charges per unit?

#Output --->
#Each person's share of the total expenses

print("----------- Welcome to the Money Splitter App! -----------")
name = input("What can I call you? \n ")
print(f"Hello {name} :), let's split the expenses among your group!")
print("Please answer the following questions carefully.")
print("----------------------------------------------------------")
pepole = int(input("Q1: How many people are there in the group? \n"))
rent = float(input("Q2: What is the total amount of money spent on rent? \n"))
food = float(input("Q3: What is the total amount of money spent on food? \n"))
electricity_units = int(input("Q4: How many units of electricity were consumed? \n"))
electricity_charges_per_unit = float(input("Q5: What is the electricity charges per unit? \n"))
print(f"Thank you {name} for providing the details.")
print("----------------------------------------------------------")


#Calculation---->
total_expenses = rent + food + (electricity_units * electricity_charges_per_unit)
each_person_share = total_expenses / pepole

print("----------------------------------------------------------")
print(f"Total expenses: Rs. {total_expenses:.2f}")
print(f"Each person's share: Rs. {each_person_share:.2f}")
print(f"Thank you {name} for using the Money Splitter App! Have a great day!")
print("----------------------------------------------------------")